inline void draw_char(SDL_Renderer* ren, char c, int x, int y, int scale, SDL_Color color) {
    if (c >= 'a' && c <= 'z') c -= 32;
    int idx = c - 32;
    if (c == '%') idx = 5;
    if (idx < 0 || idx > 95) return;
    const uint8_t* glyph = FONT8x8[idx];
    SDL_SetRenderDrawColor(ren, color.r, color.g, color.b, color.a);
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (0x80 >> col)) {
                SDL_Rect r{ x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(ren, &r);
            }
        }
    }
}

inline void draw_text(SDL_Renderer* ren, const std::string& text, int x, int y, int scale, SDL_Color color, bool shadow = true) {
    if (shadow) {
        SDL_Color shadow_col{ 5, 8, 12, 180 };
        for (size_t i = 0; i < text.size(); ++i) {
            draw_char(ren, text[i], x + (int)i * 8 * scale + scale, y + scale, scale, shadow_col);
        }
    }
    for (size_t i = 0; i < text.size(); ++i) {
        draw_char(ren, text[i], x + (int)i * 8 * scale, y, scale, color);
    }
}

inline int get_text_width(const std::string& text, int scale) {
    return static_cast<int>(text.size()) * 8 * scale;
}
