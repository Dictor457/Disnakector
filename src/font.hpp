inline void draw_char(SDL_Renderer* ren, char c, int x, int y, int scale, SDL_Color color) {
    if (c >= 'a' && c <= 'z') c -= 32;
    int idx = c - 32;
    if (c == '%') idx = 5;
    if (idx < 0 || idx > 95) return;
    const uint8_t* glyph = FONT8x8[idx];
    SDL_SetRenderDrawColor(ren, color.r, color.g, color.b, color.a);
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (0x80 >> col)) {
                SDL_Rect r{ x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(ren, &r);
            }
        }
    }
}

inline void draw_cyr_char(SDL_Renderer* ren, int idx, int x, int y, int scale, SDL_Color color) {
    if (idx < 0 || idx > 32) return;
    const uint8_t* glyph = FONT_CYR[idx];
    SDL_SetRenderDrawColor(ren, color.r, color.g, color.b, color.a);
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (0x80 >> col)) {
                SDL_Rect r{ x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(ren, &r);
            }
        }
    }
}

inline void draw_text(SDL_Renderer* ren, const std::string& text, int x, int y, int scale, SDL_Color color, bool shadow = true) {
    int cur_x = x;
    for (size_t i = 0; i < text.size(); ) {
        uint8_t b1 = static_cast<uint8_t>(text[i]);
        if (b1 < 0x80) {
            if (shadow) draw_char(ren, text[i], cur_x + scale, y + scale, scale, {5, 8, 12, 180});
            draw_char(ren, text[i], cur_x, y, scale, color);
            cur_x += 8 * scale;
            i++;
        } else if (b1 == 0xD0 || b1 == 0xD1) {
            if (i + 1 < text.size()) {
                uint8_t b2 = static_cast<uint8_t>(text[i + 1]);
                int cyr_idx = -1;
                if (b1 == 0xD0) {
                    if (b2 == 0x81) cyr_idx = 32;
                    else if (b2 >= 0x90 && b2 <= 0xAF) cyr_idx = b2 - 0x90;
                    else if (b2 >= 0xB0 && b2 <= 0xBF) cyr_idx = b2 - 0xB0;
                } else if (b1 == 0xD1) {
                    if (b2 == 0x91) cyr_idx = 32;
                    else if (b2 >= 0x80 && b2 <= 0x8F) cyr_idx = 16 + (b2 - 0x80);
                }
                if (cyr_idx >= 0 && cyr_idx < 33) {
                    if (shadow) draw_cyr_char(ren, cyr_idx, cur_x + scale, y + scale, scale, {5, 8, 12, 180});
                    draw_cyr_char(ren, cyr_idx, cur_x, y, scale, color);
                }
                cur_x += 8 * scale;
                i += 2;
            } else {
                i++;
            }
        } else {
            i++;
        }
    }
}

inline int get_text_width(const std::string& text, int scale) {
    int count = 0;
    for (size_t i = 0; i < text.size(); ) {
        uint8_t b = static_cast<uint8_t>(text[i]);
        if (b < 0x80) { count++; i++; }
        else if (b == 0xD0 || b == 0xD1) { count++; i += 2; }
        else { i++; }
    }
    return count * 8 * scale;
}
